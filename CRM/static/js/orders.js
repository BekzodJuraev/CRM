 // Initialize when the DOM is loaded
        document.addEventListener('DOMContentLoaded', function() {
            // Find all category selectors
            const selectors = document.querySelectorAll('.form-select');

            selectors.forEach(selector => {
                // Add change event listener
                selector.addEventListener('change', function() {
                    const selectedCategory = this.value;
                    const selectedData = categoriesMap[selectedCategory] || [];

                    // Find the associated dropdown list
                    const parentContainer = this.closest('.category-group');
                    const dropdownList = parentContainer.querySelector('.dropdown-options');

                    if (dropdownList) {
                        buildDropdown(selectedData, dropdownList);
                    }
                });

                // Initialize with default category if available
                const selectedCategory = selector.value;
                if (selectedCategory) {
                    const selectedData = categoriesMap[selectedCategory] || [];
                    const parentContainer = selector.closest('.category-group');
                    const dropdownList = parentContainer.querySelector('.dropdown-options');

                    if (dropdownList) {
                        buildDropdown(selectedData, dropdownList);
                    }
                }
            });
        });

        // Function to build menu hierarchy
        function buildMenu(items, container, path = []) {
            container.innerHTML = ""; // Clear existing items

            items.forEach(item => {
                const li = document.createElement("li");
                li.textContent = item.label;

                const currentPath = [...path, item.label];

                // Check for subItems and add submenu
                if (item.subItems && item.subItems.length > 0) {
                    li.classList.add("has-submenu");
                    const subUl = document.createElement("ul");
                    subUl.className = "submenu";
                    buildMenu(item.subItems, subUl, currentPath);
                    li.appendChild(subUl);

                    // Hover functionality for submenu
                    li.addEventListener("mouseover", () => {
                        subUl.style.display = "block";
                    });
                    li.addEventListener("mouseleave", () => {
                        subUl.style.display = "none";
                    });
                }

                // Add click listener for all items
                li.addEventListener("click", function(e) {
                    e.stopPropagation();
                    if (!item.subItems || item.subItems.length === 0) {
                        // Find the closest custom-dropdown parent
                        const dropdownElement = this.closest('.custom-dropdown');
                        selectOption(currentPath, dropdownElement);
                    }
                });

                container.appendChild(li);
            });
        }

        // Function to select an option and update the display
        function selectOption(pathArray, dropdownElement) {
            const value = pathArray.join(", ");

            // Update the display and hidden input
            const selectedElement = dropdownElement.querySelector(".selected");
            const inputElement = dropdownElement.querySelector("input[type='hidden']");
            const dropdownList = dropdownElement.querySelector(".dropdown-options");

            if (selectedElement) selectedElement.textContent = value;
            if (inputElement) inputElement.value = value;
            if (dropdownList) dropdownList.style.display = "none";
        }

        // Function to build a dropdown
        function buildDropdown(data = [], dropdownList) {
            if (!dropdownList) return;
            buildMenu(data, dropdownList);
        }

        // Toggle dropdown visibility function
        function toggleDropdown(element) {
    // If element is null or undefined, return early
    if (!element) {
        console.error("toggleDropdown: Element is undefined");
        return;
    }

    const dropdownContainer = element.closest('.custom-dropdown');
    if (!dropdownContainer) {
        console.error("toggleDropdown: Could not find parent .custom-dropdown");
        return;
    }

    const dropdownList = dropdownContainer.querySelector('.dropdown-options');
    if (!dropdownList) {
        console.error("toggleDropdown: Could not find .dropdown-options");
        return;
    }

    // Close all other dropdowns first
    document.querySelectorAll('.dropdown-options').forEach(list => {
        if (list !== dropdownList && list.style.display === "block") {
            list.style.display = "none";
        }
    });

    // Toggle this dropdown
    dropdownList.style.display = dropdownList.style.display === "block" ? "none" : "block";
}

